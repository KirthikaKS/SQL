--- INNER JOIN / JOIN

--- fetch the employee name and the department name they belong to.
--- When joining the column name doest not matter they values have to match that is important


SELECT EMP_NAME,DEPT_NAME
FROM EMPLOYEE
INNER JOIN DEPARTMENT ON EMPLOYEE.DEPT_ID = DEPARTMENT.DEPT_ID;

---- fetch the details of all the employee name and their department name

---- LEFT JOIN WILL DO AN INNER JOIN FIRST AND THE ADDITIONALLY IT WILL CHECK FOR ADDITIONAL RECORD FROM LEFT JOIN THAT WERE NOT INCLUDED IN THE INNER JOIN

--- BY LEFT AND RIGHT IT MEANS THAT THE TABLE MENTIONED ON THE LEFT OF THE JOIN KEYWORD AND RIGHT OF THE JOIN KEYWORD

--- LEFT JOIN OR LEFT OUTER JOIN

SELECT EMP_NAME,DEPT_NAME
FROM EMPLOYEE
LEFT JOIN DEPARTMENT ON EMPLOYEE.DEPT_ID = DEPARTMENT.DEPT_ID;

--- RIGHT JOIN OR RIGHT OUTER JOIN

SELECT EMP_NAME,DEPT_NAME
FROM EMPLOYEE
RIGHT JOIN DEPARTMENT ON EMPLOYEE.DEPT_ID = DEPARTMENT.DEPT_ID;

