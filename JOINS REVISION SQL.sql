--- WE HAVE TO USE ALL TABLES SO WE HAVE TO JOIN ALL OF THEM

--- YOU HAVE TO KEEP THE PRIMARY TABLE AS THE TABLE FROM WHICH YOU NEED ALL RECORDS

SELECT E.EMP_NAME,D.DEPT_NAME,M.MANAGER_NAME,P.PROJECT_NAME
FROM EMPLOYEE E
LEFT JOIN DEPARTMENT D ON E.DEPT_ID = D.DEPT_ID
INNER JOIN MANAGER M ON E.MANAGER_ID = M.MANAGER_ID
LEFT JOIN PROJECTS P ON E.EMP_ID = P.TEAM_MEMBER_ID;

------ THE LAST LEFT JOIN IN THE ABOVE QUERY CONSIDERS THE OUTPUT OF ALL QUERIES ABOVE IT THAT IS ALL THE JOINS NOT ONLY THE IMMEDIATE JON ABOVE IT 

--- FULL OUTER JOIN/ FULL JOIN
--- FIRST DOES INNER JOIN FIRST, THEN LOOKS INTO LEFT TABLE FETCHES THE ONES LEFT OUT FROM INNER JOIN
--- THEN FETCHES THE LEFT ONES FROM RIGHT TABLE

SELECT EMP_NAME,DEPT_NAME
FROM EMPLOYEE
FULL JOIN DEPARTMENT ON EMPLOYEE.DEPT_ID = DEPARTMENT.DEPT_ID;


